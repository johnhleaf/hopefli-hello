#!/usr/bin/env bash
set -euo pipefail
APP_DIR="${APP_DIR:-/opt/hopefli-intranet}"
[[ $EUID -eq 0 ]] || { echo "Kör med sudo."; exit 1; }
command -v docker >/dev/null || { echo "Docker saknas."; exit 1; }
command -v curl >/dev/null || { echo "curl saknas."; exit 1; }
command -v systemctl >/dev/null || { echo "systemd/systemctl saknas."; exit 1; }
if ! command -v git >/dev/null; then
  echo "Installerar git för GitHub-synk..."
  apt-get update -qq
  DEBIAN_FRONTEND=noninteractive apt-get install -y -qq git >/dev/null
fi
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT
PAYLOAD="$TMP/hopefli-hello-v0.1.8.tar.gz"
LINE=$(awk '/^#__HOPEFLI_PAYLOAD_BELOW__$/ {print NR + 1; exit 0;}' "$0")
[[ -n "$LINE" ]] || { echo "Payload saknas."; exit 1; }
tail -n +"$LINE" "$0" | sed 's/^#//' | base64 -d > "$PAYLOAD"

echo "Packar upp Hopefli Hello v0.1.8..."
tar -xzf "$PAYLOAD" -C "$TMP"
ROOT="$TMP/hopefli-hello-v0.1.8"
[[ -f "$ROOT/VERSION" && -f "$ROOT/docker-compose.yml" ]] || { echo "Ogiltigt releasepaket."; exit 1; }
find "$ROOT" -type d -exec chmod 755 {} +
find "$ROOT" -type f -exec chmod 644 {} +
chmod 755 "$ROOT/install.sh" "$ROOT/update.sh" "$ROOT/scripts/hello-worker.sh" "$ROOT/scripts/github-sync.sh"
VERSION=$(cat "$ROOT/VERSION")
REL="$APP_DIR/releases/$VERSION"
mkdir -p "$APP_DIR/releases" "$APP_DIR/backups" "$APP_DIR/shared/hello-config" "$APP_DIR/shared/update-inbox"
chown 10001:10001 "$APP_DIR/shared/hello-config" "$APP_DIR/shared/update-inbox"
chmod 700 "$APP_DIR/shared/hello-config"
chmod 750 "$APP_DIR/shared/update-inbox"
[[ ! -e "$REL" ]] || rm -rf "$REL"

echo "Testbygger releasen..."
docker build -t "hopefli-hello-test:$VERSION" "$ROOT" >/dev/null
docker run --rm -e PYTHONPYCACHEPREFIX=/tmp/pycache "hopefli-hello-test:$VERSION" python -m compileall -q /app/app

TS=$(date +%Y%m%d-%H%M%S)
PREV=$(readlink -f "$APP_DIR/current" 2>/dev/null || true)
tar -czf "$APP_DIR/backups/pre-update-$TS-config.tar.gz" -C "$APP_DIR" shared/.env shared/hello-config docker-compose.yml 2>/dev/null || true
cp -a "$ROOT" "$REL"
ln -sfn "$REL" "$APP_DIR/current"
cp "$REL/docker-compose.yml" "$APP_DIR/docker-compose.yml"

install -m 0755 "$REL/scripts/hello-worker.sh" /usr/local/sbin/hopefli-hello-worker
install -m 0644 "$REL/scripts/hopefli-hello-worker.service" /etc/systemd/system/hopefli-hello-worker.service
install -m 0644 "$REL/scripts/hopefli-hello-worker.path" /etc/systemd/system/hopefli-hello-worker.path
systemctl daemon-reload
systemctl enable --now hopefli-hello-worker.path >/dev/null

cd "$APP_DIR"
if [[ -f "$APP_DIR/shared/.env" ]]; then set -a; source "$APP_DIR/shared/.env"; set +a; fi
if docker compose build app && docker compose up -d; then
  sleep 3
  if curl -fsS "http://127.0.0.1:${APP_PORT:-8097}/health" >/dev/null; then
    echo
    echo "Klart: Hopefli Hello v$VERSION körs."
    echo "Webbadministration: https://hello.hopefli.se/admin/system"
    echo "Från och med nu kan kommande .tar.gz-releaser installeras därifrån."
    exit 0
  fi
fi

echo "Uppdateringen startade inte korrekt – återställer föregående release."
if [[ -n "$PREV" && -d "$PREV" ]]; then
  ln -sfn "$PREV" "$APP_DIR/current"
  cp "$PREV/docker-compose.yml" "$APP_DIR/docker-compose.yml" 2>/dev/null || true
  docker compose build app || true
  docker compose up -d || true
fi
exit 1
